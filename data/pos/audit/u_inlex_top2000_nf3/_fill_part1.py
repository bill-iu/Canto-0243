        "- 動作成語／動短 → v：一飲而盡、揚長而去、借刀殺人、瞞天過海、釜底抽薪…",
        "- 狀態成語 → a：喜氣洋洋、精神抖擻、劍拔弩張、忠心耿耿、麻木不仁…",
        "- 副詞／時間：一個勁兒／轉瞬間／一時半會／從早到晚 → r",
