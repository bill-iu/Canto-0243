def _norm_pos(pos: str) -> str:
    if pos == "u":
        return "u"
    tags = sorted(set(t.strip() for t in pos.split(",") if t.strip()))
    order = {"a": 0, "n": 1, "r": 2, "v": 3, "x": 4}
    tags.sort(key=lambda t: order[t])
    return ",".join(tags)


