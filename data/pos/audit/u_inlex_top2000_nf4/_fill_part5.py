ORDER = "anrvx"


def _norm_pos(pos: str) -> str:
    tags = [t.strip() for t in pos.split(",") if t.strip()]
    return ",".join(sorted(set(tags), key=lambda t: ORDER.index(t) if t in ORDER else 99))


def fill() -> list[dict]:
    rows: list[dict] = []
    with TSV.open(encoding="utf-8", newline="") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            lit = (r.get("literal") or "").strip()
            if lit not in L:
                raise SystemExit(f"missing label: {lit!r}")
            pos, fam, note = L[lit]
            pos = _norm_pos(pos)
            if fam not in ("", "idiom"):
                raise SystemExit(f"bad family {fam!r} for {lit}")
            if pos != "u":
                for t in pos.split(","):
                    if t not in set(ORDER):
                        raise SystemExit(f"bad pos {pos!r} for {lit}")
            rows.append(
                {
                    "literal": lit,
                    "freq": r.get("freq") or "",
                    "pos": pos,
                    "family": fam,
                    "voice": "",
                    "note": note,
                }
            )
    if len(rows) != 400:
        raise SystemExit(f"expected 400 rows, got {len(rows)}")
    if len(L) != 400:
        raise SystemExit(f"expected 400 labels, got {len(L)}")
    with TSV.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(
            fh,
            fieldnames=["literal", "freq", "pos", "family", "voice", "note"],
            delimiter="\t",
            lineterminator="\n",
        )
        w.writeheader()
        w.writerows(rows)
    return rows


