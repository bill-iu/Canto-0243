    u_rows: list[tuple[str, str]] = []
    multi = 0

    out_rows = []
    for r in rows:
        lit = r["literal"]
        pos, fam, note = L[lit]
        pos = norm_pos(pos)
        if fam not in ("", "idiom"):
            raise SystemExit(f"bad family {fam!r} for {lit}")
        if pos == "u":
            keep_u += 1
            u_rows.append((lit, note or "fragment/opaque"))
        else:
            formal += 1
            tags = pos.split(",")
            if len(tags) > 1:
                multi += 1
            for t in tags:
                tag_c[t] += 1
        pos_c[pos] += 1
        if fam == "idiom":
            idioms.append((lit, pos))
        out_rows.append(
            {
                "literal": lit,
                "freq": r["freq"],
                "pos": pos,
                "family": fam,
                "voice": "",
                "note": note,
            }
        )

