def norm_pos(raw: str) -> str:
    tags = [t.strip() for t in raw.split(",") if t.strip()]
    if raw.strip() == "u":
        return "u"
    bad = [t for t in tags if t not in ALLOWED]
    if bad:
        raise ValueError(f"bad tags {bad} in {raw!r}")
    return ",".join(sorted(set(tags), key=lambda t: ORDER.index(t)))


