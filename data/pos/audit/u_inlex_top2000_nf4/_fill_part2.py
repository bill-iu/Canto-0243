def main() -> None:
    rows_in = list(csv.DictReader(TSV.open(encoding="utf-8"), delimiter="\t"))
    assert len(rows_in) == 400, len(rows_in)
    missing = [r["literal"] for r in rows_in if r["literal"] not in L]
    extra = set(L) - {r["literal"] for r in rows_in}
    if missing or extra:
        raise SystemExit(f"missing={missing[:20]} extra={list(extra)[:20]}")

    out_rows = []
    pos_c: Counter[str] = Counter()
    tag_c: Counter[str] = Counter()
    fam_c: Counter[str] = Counter()
    formal = u_n = multi = 0
    idioms: list[tuple[str, str]] = []
    u_list: list[str] = []

    for r in rows_in:
        lit = r["literal"]
        pos, fam, note = L[lit]
        tags = [t for t in pos.split(",") if t]
        assert tags and all(t in "nvarx" or t == "u" for t in tags), (lit, pos)
        assert tags == sorted(set(tags)) or pos == "u", (lit, pos)
        assert fam in ("", "idiom"), fam
        if pos == "u":
            u_n += 1
            u_list.append(lit)
        else:
            formal += 1
            if len(tags) > 1:
                multi += 1
            for t in tags:
                tag_c[t] += 1
        pos_c[pos] += 1
        fam_c[fam or "empty"] += 1
