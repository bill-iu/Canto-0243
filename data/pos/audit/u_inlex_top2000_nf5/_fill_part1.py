def _norm_pos(pos: str) -> str:
    tags = [t.strip() for t in pos.split(",") if t.strip()]
    order = {"a": 0, "n": 1, "r": 2, "v": 3, "x": 4, "u": 5}
    return ",".join(sorted(set(tags), key=lambda t: order.get(t, 9)))


def main() -> None:
    with SRC.open(encoding="utf-8", newline="") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    missing = [r["literal"] for r in rows if r["literal"] not in LABELS]
    extra = sorted(set(LABELS) - {r["literal"] for r in rows})
    if missing:
        raise SystemExit(f"missing labels ({len(missing)}): {missing[:20]}")
    if extra:
        raise SystemExit(f"extra labels ({len(extra)}): {extra[:20]}")

    out_rows = []
    pos_c: Counter[str] = Counter()
    tag_c: Counter[str] = Counter()
    idiom_rows: list[tuple[str, str]] = []
    formal = u_n = multi = 0
    for r in rows:
        lit = r["literal"]
        pos, fam, note = LABELS[lit]
        pos = _norm_pos(pos)
        if fam not in ("", "idiom"):
            fam = ""
        voice = ""
        if pos == "u":
            u_n += 1
        else:
            formal += 1
        if "," in pos:
            multi += 1
        pos_c[pos] += 1
        for t in pos.split(","):
            tag_c[t] += 1
        if fam == "idiom":
            idiom_rows.append((lit, pos))
        out_rows.append(
            {
                "literal": lit,
                "freq": r["freq"],
                "pos": pos,
                "family": fam,
                "voice": voice,
                "note": note,
            }
        )

    with SRC.open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(
            fh,
            fieldnames=["literal", "freq", "pos", "family", "voice", "note"],
            delimiter="\t",
            lineterminator="\n",
        )
        w.writeheader()
        w.writerows(out_rows)

