def main() -> None:
    heads = [
        ln.strip()
        for ln in HEADS_PATH.read_text(encoding="utf-8").splitlines()
        if ln.strip()
    ]
    prop_rows: list[tuple[str, str]] = []
    covered: set[str] = set()
    for h in heads:
        for t in PROPOSALS.get(h, []):
            if not t or "entangle" in t or "pen" in t:
                continue
            # drop junk tails from typos
            if any(c.isascii() and c.isalpha() for c in t):
                continue
            prop_rows.append((h, t))
            covered.add(h)

    nn_rows: list[tuple[str, str, str]] = []
    for h in heads:
        if h in covered:
            continue
        if h in PROPER:
            reason = "proper_name_or_deixis"
        elif any(h.endswith(s) for s in ("大學", "公司", "銀行", "部長", "政府", "學院")):
            reason = "no_gradable_opposite"
        elif h.endswith(("亞", "蘭", "斯坦")) or "爾" in h and len(h) == 4 and h in PROPER:
            reason = "proper_name_or_deixis"
        else:
            reason = "no_gradable_opposite"
        nn_rows.append((h, reason, BATCH_ID))

    OUT_PROP.parent.mkdir(parents=True, exist_ok=True)
    with OUT_PROP.open("w", encoding="utf-8", newline="\n") as f:
        f.write("head\ttail\n")
        for h, t in prop_rows:
            f.write(f"{h}\t{t}\n")
    with OUT_NN.open("w", encoding="utf-8", newline="\n") as f:
        f.write("head\treason\tbatch_id\n")
        for h, r, b in nn_rows:
            f.write(f"{h}\t{r}\t{b}\n")
    print(
        json.dumps(
            {
                "heads": len(heads),
                "proposal_pairs": len(prop_rows),
                "heads_with_proposals": len(covered),
                "no_natural_draft": len(nn_rows),
                "sum": len(covered) + len(nn_rows),
            },
            ensure_ascii=False,
            indent=2,
        )
    )


